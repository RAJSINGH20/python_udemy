# Integer Operations Example


# Addition
black_tea_grams = 14
ginger_grams = 3

total_grams = black_tea_grams + ginger_grams

print(f"Total grams of tea mixture : {total_grams} g")


# Subtraction
remaining_tea = black_tea_grams - ginger_grams

print(f"Remaining black tea grams  : {remaining_tea} g")


# Division
milk_liters = 7
servings = 4

milk_per_serving = milk_liters / servings

print(f"\nMilk per serving : {milk_per_serving} liters")


# Floor Division
total_tea_bags = 7
pots = 4

tea_bags_per_pot = total_tea_bags // pots

print(f"Tea bags per pot : {tea_bags_per_pot}")


# Modulus Operator
total_cardamom_pods = 10
pods_per_tea = 3

leftover_pods = total_cardamom_pods % pods_per_tea

print(f"Leftover cardamom pods : {leftover_pods}")


# Exponentiation
base_flavour_strength = 2
scale_factor = 3

powerful_flavour_strength = base_flavour_strength ** scale_factor

print(f"\nPowerful flavour strength : {powerful_flavour_strength}")


# Large Integer Example
total_tea_leaves_harvested = 1_000_000_000

print(f"Total tea leaves harvested : {total_tea_leaves_harvested}")