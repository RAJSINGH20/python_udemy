def eilaichi(
    flavor = "eilaichi",
    milk = "full cream",
    sugar = "2 tsp",
    water = "1 cup",
):
    """Return a string describing the flavor of eilaichi chai."""
    return f"The flavor of this chai is {flavor}, made with {milk} milk, {sugar} sugar, and {water} water."

